//! 36-Hero Theme-Defined Roster (`MOBA_HEROES`) organized by the 3-Type Core Taxonomy:
//! - **14 `HeroType::Brawler`** (Melee Physical / Magic / Hybrid)
//! - **12 `HeroType::Damage`** (Ranged Physical / Magic / Hybrid)
//! - **10 `HeroType::Support`** (Ranged Magic / Hybrid)
//!
//! Every hero has pre-mapped 3D Vanilla WoW appearance (`survivors_idx`, `display_override`,
//! `weapons`), explicit `HeroType`, `DamageProfile`, `themes: &'static [ThemeTag]`, base `armor`
//! & `magic_resist`, and a bespoke 6-slot action-MOBA kit (`Auto + Q + W + E + Dual R + F`).

use super::data::{
    CcCategory, DamageProfile, HeroRole, HeroType, MobaAbilityDef, MobaAbilitySlot, MobaEffect,
    PowerType, ThemeTag,
};

#[allow(clippy::too_many_arguments)]
const fn ab(
    key: &'static str,
    name: &'static str,
    spell_id: u32,
    slot: MobaAbilitySlot,
    cooldown: f32,
    power_cost: f32,
    damage: f32,
    heal: f32,
    range: f32,
    radius: f32,
    effect: MobaEffect,
    desc: &'static str,
) -> MobaAbilityDef {
    MobaAbilityDef {
        key,
        name,
        spell_id,
        slot,
        cooldown,
        power_cost,
        damage,
        heal,
        range,
        radius,
        effect,
        desc,
    }
}

/// Complete definition of one of the 36 Theme-Defined Heroes in the 5v5 Mid Brawl.
#[derive(Clone, Copy, Debug)]
pub struct MobaHeroDef {
    pub idx: usize,
    pub key: &'static str,
    pub name: &'static str,
    pub title: &'static str,
    /// Core 3-type classification (`Brawler`, `Damage`, `Support`).
    pub hero_type: HeroType,
    /// Damage profile (`Physical`, `Magic`, `Hybrid`).
    pub damage_profile: DamageProfile,
    /// Legacy 4-role compatibility (`Tank`, `Healer`, `MeleeDps`, `RangedDps`).
    pub role: HeroRole,
    /// Elemental, weapon, and tactical theme tags (`2..=4` tags).
    pub themes: &'static [ThemeTag],
    /// Underlying `MOBA_CLASSES` / `survivors::data::CLASSES` index (`0..9`) for animations/icons.
    pub class_idx: usize,
    /// Optional creature `CreatureDisplayInfo.dbc` override (e.g. Flesh Golem, Molten Giant, Lich, Crypt Lord).
    pub display_override: Option<u32>,
    /// Weapon item IDs `[main_hand, off_hand, ranged]`.
    pub weapons: &'static [u32],
    pub sheath: u8,
    pub scale: f32,
    pub color: u32,
    pub power_type: PowerType,
    pub base_hp: f32,
    pub base_power: f32,
    pub base_armor: f32,
    pub base_magic_resist: f32,
    pub base_speed: f32,
    pub attack_range: f32,
    pub auto_primary: MobaAbilityDef,
    pub q_skill: MobaAbilityDef,
    pub w_skill: MobaAbilityDef,
    pub e_skill: MobaAbilityDef,
    pub ultimates: [MobaAbilityDef; 2],
    pub mobility: MobaAbilityDef,
}

impl MobaHeroDef {
    pub fn has_theme(&self, tag: ThemeTag) -> bool {
        self.themes.contains(&tag)
    }

    pub fn theme_summary(&self) -> String {
        self.themes
            .iter()
            .map(|t| t.label())
            .collect::<Vec<_>>()
            .join(" · ")
    }

    pub fn themes_summary(&self) -> String {
        self.theme_summary()
    }

    pub const fn default_race(&self) -> u8 {
        const RACES: [u8; 8] = [1, 2, 3, 4, 5, 6, 7, 8];
        RACES[self.idx % RACES.len()]
    }

    pub const fn default_sex(&self) -> u8 {
        (self.idx & 1) as u8
    }
}

