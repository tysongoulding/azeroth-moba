pub fn moba_hero_by_index(idx: usize) -> &'static MobaHeroDef {
    &MOBA_HEROES[idx.min(MOBA_HEROES.len() - 1)]
}

pub fn moba_hero_by_key(key: &str) -> Option<&'static MobaHeroDef> {
    MOBA_HEROES.iter().find(|h| h.key == key)
}

pub fn heroes_by_type(hero_type: HeroType) -> Vec<&'static MobaHeroDef> {
    MOBA_HEROES
        .iter()
        .filter(|h| h.hero_type == hero_type)
        .collect()
}

pub fn heroes_by_theme(theme: ThemeTag) -> Vec<&'static MobaHeroDef> {
    MOBA_HEROES
        .iter()
        .filter(|h| h.has_theme(theme))
        .collect()
}
