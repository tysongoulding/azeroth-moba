pub fn moba_class_by_id(id: u8) -> &'static MobaClassDef {
    MOBA_CLASSES
        .iter()
        .find(|c| c.id == id)
        .unwrap_or(&MOBA_CLASSES[0])
}

pub fn moba_class_by_index(idx: usize) -> &'static MobaClassDef {
    &MOBA_CLASSES[idx.min(MOBA_CLASSES.len() - 1)]
}

