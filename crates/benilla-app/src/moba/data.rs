/// Shop item definition.
#[derive(Clone, Copy, Debug)]
pub struct ShopItemDef {
    pub key: &'static str,
    pub name: &'static str,
    pub spell_id: u32,
    pub category: ShopCategory,
    pub cost: u32,
    pub bonus_hp: f32,
    pub bonus_might: f32,
    pub bonus_armor: f32,
    pub bonus_speed_pct: f32,
    pub bonus_haste: f32,
    pub bonus_crit: f32,
    pub bonus_regen: f32,
    pub bonus_area: f32,
    pub active: ActiveItemEffect,
    pub active_cd: f32,
    pub desc: &'static str,
}

impl ShopItemDef {
    pub const fn is_active(&self) -> bool {
        !matches!(self.active, ActiveItemEffect::None)
    }

    pub const fn primary_stat_hint(&self) -> Stat {
        if self.bonus_might >= 0.15 {
            Stat::Might
        } else if self.bonus_hp >= 120.0 {
            Stat::MaxHp
        } else if self.bonus_speed_pct > 0.0 {
            Stat::Speed
        } else {
            Stat::Armor
        }
    }
}

