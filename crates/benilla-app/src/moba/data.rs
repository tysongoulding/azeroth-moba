//! - `Team` (`Alliance`, `Horde`) and `HeroRole` (`Tank`, `Healer`, `MeleeDps`, `RangedDps`)
//! - All 9 Vanilla WoW 1.12 classes with hybrid action-MOBA kits (`auto_primary`, `Q`, `W`, `E`,
//!   `ultimates: [MobaAbilityDef; 2]`, and `F` `mobility`)
//! - 4 iconic single-lane WoW Mid-Corridor Battlegrounds (`MOBA_MAPS`)
//! - 20 Vanilla WoW 1.12 shop items (`SHOP_ITEMS`) with passive stats and active PvP trinkets

use crate::survivors::data::Stat;

/// Faction team in the 5v5 Mid Brawl.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, Default)]
pub enum Team {
    #[default]
    Alliance,
    Horde,
}

impl Team {
    pub const fn opposite(self) -> Self {
        match self {
            Self::Alliance => Self::Horde,
            Self::Horde => Self::Alliance,
        }
    }

    pub const fn name(self) -> &'static str {
        match self {
            Self::Alliance => "Alliance",
            Self::Horde => "Horde",
        }
    }

    /// Direction along the mid corridor X axis: Alliance marches `+1.0` (`-X -> +X`),
    /// Horde marches `-1.0` (`+X -> -X`).
    pub const fn dir_sign(self) -> f32 {
        match self {
            Self::Alliance => 1.0,
            Self::Horde => -1.0,
        }
    }

    /// `FactionTemplate.dbc` ID used for 3D unit nameplates and hostility.
    pub const fn faction_template(self) -> u32 {
        match self {
            Self::Alliance => 35,
            Self::Horde => 14,
        }
    }

    pub const fn default_races(self) -> &'static [u8] {
        match self {
            Self::Alliance => &[1, 3, 4, 7],
            Self::Horde => &[2, 5, 6, 8],
        }
    }
}

/// Core 5-man combat role used for Tavern Bench Shuffle role balancing and AI bot behavior.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum HeroRole {
    Tank,
    Healer,
    MeleeDps,
    RangedDps,
}

impl HeroRole {
    pub const fn is_dps(self) -> bool {
        matches!(self, Self::MeleeDps | Self::RangedDps)
    }

    pub const fn label(self) -> &'static str {
        match self {
            Self::Tank => "Tank",
            Self::Healer => "Healer",
            Self::MeleeDps => "Melee DPS",
            Self::RangedDps => "Ranged DPS",
        }
    }
}

/// Resource bar type (`UNIT_FIELD_BYTES_0` byte 3).
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum PowerType {
    Mana = 0,
    Rage = 1,
    Energy = 3,
}

/// Classic WoW 1.12 15-second PvP Diminishing Returns (DR) categories.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum CcCategory {
    Stun = 0,
    Root = 1,
    Fear = 2,
    Silence = 3,
}

impl CcCategory {
    pub const fn index(self) -> usize {
        self as usize
    }

    pub const fn label(self) -> &'static str {
        match self {
            Self::Stun => "Stun",
            Self::Root => "Root",
            Self::Fear => "Fear",
            Self::Silence => "Silence",
        }
    }
}

/// Secondary combat or crowd-control effect attached to an ability.
#[derive(Clone, Copy, PartialEq, Debug)]
pub enum MobaEffect {
    None,
    /// Crowd control subject to the Classic WoW 15s Diminishing Returns state machine.
    Cc {
        category: CcCategory,
        duration: f32,
    },
    /// Movement speed multiplier (e.g. `0.5` = 50% slow) for `duration` seconds.
    Slow {
        factor: f32,
        duration: f32,
    },
    /// Protective absorb shield on caster or lowest-HP ally.
    ShieldAlly {
        amount: f32,
        duration: f32,
    },
    /// Divine Shield / immunity + ally heal.
    ImmunityAndHeal {
        duration: f32,
        heal: f32,
    },
    /// Team-wide Bloodlust / Heroism aura granting haste and move speed.
    BloodlustTeam {
        haste_bonus: f32,
        speed_bonus: f32,
        duration: f32,
    },
    /// Heals the caster for `fraction` of damage dealt.
    LifeDrain {
        fraction: f32,
    },
    /// Gap-closer dash toward target or cursor, with optional stun on impact.
    Dash {
        distance: f32,
        stun_secs: f32,
    },
    /// Instant arcane teleport toward cursor.
    Blink {
        distance: f32,
    },
    /// Movement speed multiplier on self for `duration` seconds.
    HasteSelf {
        speed_mult: f32,
        duration: f32,
    },
    /// Stealth + sprint ambush for `duration` seconds.
    StealthAmbush {
        speed_mult: f32,
        duration: f32,
    },
}

/// Which hotbar slot an ability occupies.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug)]
pub enum MobaAbilitySlot {
    AutoPrimary,
    Q,
    W,
    E,
    UltimateR,
    MobilityF,
}

impl MobaAbilitySlot {
    pub const fn hotkey_label(self) -> &'static str {
        match self {
            Self::AutoPrimary => "AUTO",
            Self::Q => "Q",
            Self::W => "W",
            Self::E => "E",
            Self::UltimateR => "R",
            Self::MobilityF => "F",
        }
    }
}

/// One ability in a class's hybrid action-MOBA kit.
#[derive(Clone, Copy, Debug)]
pub struct MobaAbilityDef {
    pub key: &'static str,
    pub name: &'static str,
    /// `Spell.dbc` ID for icon, cast animation, and spell visuals.
    pub spell_id: u32,
    pub slot: MobaAbilitySlot,
    pub cooldown: f32,
    /// Positive consumes Mana/Rage/Energy; negative generates Rage/Energy on hit.
    pub power_cost: f32,
    pub damage: f32,
    pub heal: f32,
    pub range: f32,
    pub radius: f32,
    pub effect: MobaEffect,
    pub desc: &'static str,
}

